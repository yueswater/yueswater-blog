"""Build themes/Chic/source/js/widgets/lang-trend.js: data + logos + widget in one file.

Usage: python3 tools/lang-trend/build.py
Data: tiobe_series.json (run fetch_tiobe.py to refresh), jobs_go.json (run fetch_jobs.py). Logos: Devicon (MIT), see logos/LICENSE-devicon.txt.
SQL is left out: it is not a general-purpose language and has no logo of its own.
"""
import json
import re
from pathlib import Path

HERE = Path(__file__).resolve().parent
OUT = HERE.parent.parent / "themes/Chic/source/js/widgets/lang-trend.js"
LOGO_FILE = {"Python": "python", "C": "c", "Java": "java", "C++": "cplusplus", "C#": "csharp",
             "JavaScript": "javascript", "Go": "go", "Visual Basic": "visualbasic", "R": "r"}

raw = json.loads((HERE / "tiobe_series.json").read_text())
series = {k: [[y * 12 + m - 1, v] for y, m, v in raw[k]] for k in LOGO_FILE}
last = max(p[0] for s in series.values() for p in s)
logos = {}
for k, f in LOGO_FILE.items():
    svg = (HERE / "logos" / f"{f}.svg").read_text().strip()
    inner = re.sub(r"^<svg[^>]*>|</svg>$", "", svg)
    if k == "Go":  # the plain Devicon Go mark has no colour of its own
        inner = f'<g fill="#00ADD8">{inner}</g>'
    logos[k] = inner
jobs_raw = json.loads((HERE / "jobs_go.json").read_text())
jobs = {k: [[t, v] for t, v in jobs_raw[k]] for k in ("permanent", "contract")}
data = {"tiobe": {"last": last, "series": series, "logos": logos},
        "jobs": {"last": max(p[0] for s in jobs.values() for p in s), "series": jobs}}
body = (HERE / "widget.js").read_text()
OUT.write_text("// Generated by tools/lang-trend/build.py. Edit the sources there, not this file.\n"
               f"const LT_DATA = {json.dumps(data, separators=(',', ':'), ensure_ascii=False)};\n" + body)
print("wrote", OUT, OUT.stat().st_size, "bytes; latest month", last // 12, last % 12 + 1)
